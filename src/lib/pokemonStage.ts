/** カード名から接尾辞・接頭辞を除去して基本のポケモン名を取得する */
function normalizeCardName(name: string): string {
  return name
    .replace(/\s*(V-UNION|VUNION|VSTAR|VMAX)$/i, '')
    .replace(/\s*V$/i, '')
    .replace(/\s*EX$/, '')    // 旧XYシリーズ大文字EX
    .replace(/\s*ex$/, '')    // SVシリーズ小文字ex
    .replace(/\s*-?GX$/i, '')
    .replace(/[（(][^）)]*のすがた[）)]/g, '')
    .replace(/[（(][^）)]+[）)]/g, '')
    .trim()
}

/**
 * ポケモンカードがたねポケモンかどうかを判定する
 * @param cardName カード記載の名前（例: "リザードンex", "かがやくゲッコウガ"）
 * @param category カードのカテゴリ（"ポケモン"以外はfalseを返す）
 */
export function isBasicPokemon(cardName: string, category: string): boolean {
  if (category !== 'ポケモン') return false

  // ルール1: かがやく〇〇 → たね
  if (cardName.startsWith('かがやく')) return true

  // ルール2: V/VUNION → たね
  if (/\s*(V-UNION|VUNION|V)$/i.test(cardName)) return true

  // ルール2b: VMAX/VSTAR → 進化（Vポケモンから進化するため）
  if (/\s*(VSTAR|VMAX)$/i.test(cardName)) return false

  // ルール3: 旧XYシリーズ大文字EX → たね
  if (/\s*EX$/.test(cardName)) return true

  // ルール4: TAG TEAM（& を含む）→ たね
  if (/[&＆]|TAG\s*TEAM/i.test(cardName)) return true

  // ルール5: カード名を正規化して進化ポケモンセットを参照
  const baseName = normalizeCardName(cardName)
  return !EVOLVED_POKEMON.has(baseName)
}
